function mk(name: string, over: Partial<MoveDef>): MoveDef {
  return {
    ...BASE,
    ...over,
    name,
    anim: { ...BASE.anim, ...(over.anim ?? {}) },
  };
}

function shot(over: Partial<ProjectileSpec>): ProjectileSpec {
  return {
    kind: "plasma",
    speed: 900,
    vy: 0,
    radius: 6,
    count: 1,
    spread: 0,
    ...over,
  };
}

const swing = (
  a0: number,
  a1: number,
  r0 = 42,
  r1 = 56,
  lift = 0,
): MoveAnim => ({ a0, a1, r0, r1, arc: "swing", lift });
const thrust = (angle: number, r0: number, r1: number): MoveAnim => ({
  a0: angle,
  a1: angle,
  r0,
  r1,
  arc: "thrust",
  lift: 0,
});
const spin = (turns = 1, r = 50): MoveAnim => ({
  a0: -1.4,
  a1: -1.4 + Math.PI * 2 * turns,
  r0: r,
  r1: r,
  arc: "spin",
  lift: 0,
});
const slam = (a0: number, a1: number, r0 = 46, r1 = 60): MoveAnim => ({
  a0,
  a1,
  r0,
  r1,
  arc: "slam",
  lift: 0,
});
const aim = (angle: number): MoveAnim => ({
  a0: angle,
  a1: angle,
  r0: 36,
  r1: 40,
  arc: "shoot",
  lift: 0,
});

