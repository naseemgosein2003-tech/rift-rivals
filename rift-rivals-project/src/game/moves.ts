/** Heavy attacks reuse the stance but trade speed for damage and knockback. */
export function heavyVariant(move: MoveDef): MoveDef {
  return {
    ...move,
    damage: Math.round(move.damage * move.multi * 1.75),
    startup: move.startup + 0.07,
    active: move.active + 0.02,
    duration: move.duration + 0.18,
    hw: move.hw * 1.15,
    hh: move.hh * 1.12,
    kb: move.kb * 1.5,
    stun: move.stun * 1.35,
    shake: move.shake * 1.4,
    hitstop: move.hitstop * 1.5,
    multi: 1,
    heavyHit: true,
    selfVx: move.selfVx * 1.15,
    selfVy: move.selfVy * 1.08,
    landingLag: move.landingLag + 0.07,
    projectile: move.projectile
      ? {
          ...move.projectile,
          radius: move.projectile.radius * 1.7,
          count: Math.max(1, move.projectile.count - 1),
          speed: move.projectile.speed * 1.05,
        }
      : undefined,
    anim: { ...move.anim, r1: move.anim.r1 * 1.08 },
  };
}

export function stanceFor(
  grounded: boolean,
  down: boolean,
  side: boolean,
): Stance {
  const plane = grounded ? "g" : "a";
  const direction = down ? "D" : side ? "S" : "N";
  return `${plane}${direction}` as Stance;
}

export function getMove(
  weapon: Weapon,
  stance: Stance,
  heavy: boolean,
): MoveDef {
  const move = MOVES[weapon][stance];
  return heavy ? heavyVariant(move) : move;
}
