import type { Weapon } from "./data";

/**
 * Every weapon has six distinct attacks: neutral, side, and down, performed
 * either grounded ("g") or airborne ("a"). Heavy versions are derived from the
 * same data so each weapon keeps a recognisable shape with more commitment.
 *
 * Stance roles are consistent across the roster so the controls stay readable:
 *   neutral - reliable launcher that starts combos
 *   side    - committed forward attack with the best reach and knockback
 *   down    - fast low poke on the ground, a spike in the air
 */
export type Stance = "gN" | "gS" | "gD" | "aN" | "aS" | "aD";

export const STANCES: Stance[] = ["gN", "gS", "gD", "aN", "aS", "aD"];

export const STANCE_LABELS: Record<Stance, string> = {
  gN: "Neutral",
  gS: "Side",
  gD: "Down",
  aN: "Air neutral",
  aS: "Air side",
  aD: "Air down",
};

export type Sfx = "slash" | "blunt" | "pierce" | "punch" | "shot" | "magic";

export interface ProjectileSpec {
  kind: string;
  speed: number;
  vy: number;
  radius: number;
  count: number;
  spread: number;
}

/** Drives the on-screen swing so every move animates differently. */
export interface MoveAnim {
  /** Weapon angle at the start and end of the active swing, in radians. */
  a0: number;
  a1: number;
  /** Distance of the weapon hand from the shoulder across the swing. */
  r0: number;
  r1: number;
  arc: "swing" | "thrust" | "spin" | "shoot" | "slam";
  /** Vertical hand offset, used to sell overhead and low attacks. */
  lift: number;
}

export interface MoveDef {
  name: string;
  damage: number;
  startup: number;
  active: number;
  duration: number;
  /** Hitbox centre, relative to the fighter's feet and facing direction. */
  hx: number;
  hy: number;
  hw: number;
  hh: number;
  /** Knockback magnitude and direction shaping. */
  kb: number;
  kbx: number;
  kby: number;
  /** Hitstun, screen shake, and freeze-frame weighting for this move. */
  stun: number;
  shake: number;
  hitstop: number;
  multi: number;
  spike: boolean;
  launch: boolean;
  pull: boolean;
  heavyHit: boolean;
  selfVx: number;
  selfVy: number;
  /** Extra recovery when an aerial lands before its animation finishes. */
  landingLag: number;
  /** Air control retained while the move is out. */
  drift: number;
  sfx: Sfx;
  projectile?: ProjectileSpec;
  anim: MoveAnim;
}

